function rewriteHtml(html) {
  return html
    .replaceAll("href=\"challenges.html\"", "href=\"/challenges\"")
    .replaceAll("href=\"about.html\"", "href=\"/about\"")
    .replaceAll("href=\"faq.html\"", "href=\"/faq\"")
    .replaceAll("href=\"index.html#", "href=\"/#")
    .replaceAll("href=\"index.html\"", "href=\"/\"")
    .replaceAll("href=\"signup.html?role=business\"", "href=\"/company/signup\"")
    .replaceAll("href=\"signup.html?role=builder\"", "href=\"/signup\"")
    .replaceAll("href=\"signup.html\"", "href=\"/signup\"")
    .replaceAll("href=\"login.html\"", "href=\"/signin\"")
    .replaceAll("href=\"dashboard.html?view=company\"", "href=\"/company\"")
    .replaceAll("href=\"dashboard.html?view=student\"", "href=\"/home\"")
    .replaceAll("href=\"dashboard.html\"", "href=\"/home\"")
    .replaceAll("src=\"assets/", "src=\"/landing/");
}

function extractMain(filename) {
  const raw = readFileSync(join(srcRoot, filename), "utf8");
  const start = raw.indexOf("<main");
  const end = raw.indexOf("</main>") + "</main>".length;
  if (start < 0 || end < "</main>".length) {
    throw new Error(`Could not find <main> in ${filename}`);
  }
  return rewriteHtml(raw.slice(start, end));
}

function toTsModule(name, html) {
  return `/* Generated by scripts/port-landing.mjs — do not edit by hand. */\nexport const ${name} = ${JSON.stringify(html)};\n`;
}

