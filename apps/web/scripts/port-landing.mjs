writeFileSync(join(outDir, "faq-markup.ts"), toTsModule("FAQ_MAIN", extractMain("faq.html")));

function scopeCss(css) {
  let scoped = css
    .replace(/:root\s*\{/g, ":scope{")
    .replace(/html\[data-audience/g, ":scope[data-audience")
    .replace(/html\.no-js/g, ":scope.no-js")
    .replace(/^html\{/gm, ":scope{")
    .replace(/^body\{/gm, ":scope{");

  return `/* Generated by scripts/port-landing.mjs from the marketing repo. */
@scope (.landing-root) {
${scoped}
}
`;
}

